export type TranslationKey = keyof typeof translations.en;

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

export function translate(locale: Locale, key: TranslationKey): string {
  return translations[locale][key] ?? translations[DEFAULT_LOCALE][key];
}

export function cityNameKey(cityId: string): TranslationKey | null {
  const key = `city.${cityId}` as TranslationKey;
  return key in translations.en ? key : null;
}
